#include<iostream>
using namespace std;;

int main(){
  char ch = 'A';
  cout << "A =" <<(int)ch << endl;
  ch = 'Z';
  cout << "Z =" << (int)ch << endl;
  ch = 'a';
  cout << "a =" <<(int)ch << endl;
  ch = 'z';
  cout << "z =" <<(int)ch << endl;
  ch = '0';
  cout << "0 =" <<(int)ch << endl;
  ch = '9';
  cout << "9 =" <<(int)ch << endl;

  return 0;
}